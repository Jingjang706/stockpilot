#!/usr/bin/env python3
"""
Generates backend/src/main/resources/db/seed/V100__demo_data.sql

The seed simulates ~40 days of business so that stock levels, stock movements,
sales, payments and purchases are all mutually consistent (the same invariants
the application services enforce). Timestamps are relative to now() so the
dashboard always has fresh-looking data.

Usage:  pip install bcrypt && python database/generate_demo_seed.py
Demo accounts (DEMO ONLY - never use in production):
    admin / Admin@12345    manager / Manager@12345    cashier / Cashier@12345
"""
import random
import pathlib
import bcrypt

random.seed(42)
OUT = pathlib.Path(__file__).resolve().parent.parent / "backend/src/main/resources/db/seed/V100__demo_data.sql"


def q(v):
    """SQL literal."""
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "TRUE" if v else "FALSE"
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def ts(minutes_ago):
    return f"now() - interval '{minutes_ago} minutes'"


def pw(p):
    return bcrypt.hashpw(p.encode(), bcrypt.gensalt(rounds=10)).decode()


lines = ["-- DEMO DATA ONLY. Generated by database/generate_demo_seed.py. Do not load in production.", ""]

# ---------------------------------------------------------------- users
users = [
    (1, "admin", "admin@stockpilot.demo", "Ava Administrator", "Admin@12345", "ADMIN"),
    (2, "manager", "manager@stockpilot.demo", "Marcus Manager", "Manager@12345", "MANAGER"),
    (3, "cashier", "cashier@stockpilot.demo", "Chloe Cashier", "Cashier@12345", "CASHIER"),
    (4, "cashier2", "cashier2@stockpilot.demo", "Daniel Cashier", "Cashier@12345", "CASHIER"),
]
for uid, un, em, fn, p, role in users:
    lines.append(
        "INSERT INTO users (id, username, email, full_name, password_hash, role, active) VALUES "
        f"({uid}, {q(un)}, {q(em)}, {q(fn)}, {q(pw(p))}, {q(role)}, TRUE);"
    )

# ---------------------------------------------------------------- categories & suppliers
categories = [(1, "Beverages"), (2, "Snacks"), (3, "Household"), (4, "Personal Care"), (5, "Stationery")]
for cid, name in categories:
    lines.append(f"INSERT INTO categories (id, name) VALUES ({cid}, {q(name)});")

suppliers = [
    (1, "FreshSip Distributors", "Liam Carter", "orders@freshsip.demo", "+1 555 0101", "12 Harbour Rd"),
    (2, "CrunchTime Foods", "Sofia Reyes", "sales@crunchtime.demo", "+1 555 0102", "88 Mill Lane"),
    (3, "HomeEase Supplies", "Noah Kim", "hello@homeease.demo", "+1 555 0103", "5 Union Street"),
    (4, "PaperTrail Wholesale", "Emma Novak", "trade@papertrail.demo", "+1 555 0104", "301 Elm Avenue"),
]
for sid, name, contact, email, phone, addr in suppliers:
    lines.append(
        "INSERT INTO suppliers (id, name, contact_name, email, phone, address) VALUES "
        f"({sid}, {q(name)}, {q(contact)}, {q(email)}, {q(phone)}, {q(addr)});"
    )

# ---------------------------------------------------------------- products
# id, sku, name, category, supplier, cost, price
P = [
    (1, "BEV-001", "Sparkling Water 500ml", 1, 1, 0.35, 0.99),
    (2, "BEV-002", "Orange Juice 1L", 1, 1, 1.20, 2.79),
    (3, "BEV-003", "Cold Brew Coffee 330ml", 1, 1, 1.10, 2.99),
    (4, "BEV-004", "Green Tea Bottle 500ml", 1, 1, 0.70, 1.89),
    (5, "BEV-005", "Energy Drink 250ml", 1, 1, 0.95, 2.49),
    (6, "SNK-001", "Salted Potato Chips 150g", 2, 2, 0.80, 2.19),
    (7, "SNK-002", "Dark Chocolate Bar 100g", 2, 2, 1.05, 2.69),
    (8, "SNK-003", "Roasted Almonds 200g", 2, 2, 2.60, 5.49),
    (9, "SNK-004", "Granola Bar (6 pack)", 2, 2, 1.80, 3.99),
    (10, "SNK-005", "Salted Pretzels 250g", 2, 2, 0.90, 2.29),
    (11, "HOU-001", "Dish Soap 500ml", 3, 3, 1.10, 2.99),
    (12, "HOU-002", "Laundry Detergent 2L", 3, 3, 4.80, 9.99),
    (13, "HOU-003", "Paper Towels (2 rolls)", 3, 3, 1.70, 3.79),
    (14, "HOU-004", "Trash Bags 30pk", 3, 3, 2.20, 4.99),
    (15, "PER-001", "Hand Soap 250ml", 4, 3, 0.95, 2.49),
    (16, "PER-002", "Toothpaste 100ml", 4, 3, 1.25, 3.19),
    (17, "PER-003", "Shampoo 400ml", 4, 3, 2.90, 6.49),
    (18, "STA-001", "Ballpoint Pens (10 pack)", 5, 4, 1.00, 2.99),
    (19, "STA-002", "A5 Notebook", 5, 4, 1.40, 3.99),
    (20, "STA-003", "Sticky Notes 6 pack", 5, 4, 1.30, 3.49),
    (21, "STA-004", "Highlighters (4 pack)", 5, 4, 1.60, 4.29),
    (22, "STA-005", "Desk Stapler", 5, 4, 3.40, 7.99),
]
prod = {p[0]: {"sku": p[1], "name": p[2], "cat": p[3], "sup": p[4], "cost": p[5], "price": p[6]} for p in P}
popularity = {i: random.choice([1, 1, 2, 3, 4, 6]) for i in prod}  # sales weight

stock = {i: 0 for i in prod}
movements = []   # (minutes_ago, product, type, change, after, unit_cost, reason, ref_type, ref_id, user)
sales = []       # dicts
purchases = []   # dicts


def add_move(minutes_ago, pid, mtype, change, unit_cost, reason, ref_type, ref_id, user):
    stock[pid] += change
    assert stock[pid] >= 0, (pid, stock[pid])
    movements.append((minutes_ago, pid, mtype, change, stock[pid], unit_cost, reason, ref_type, ref_id, user))


# ---------------------------------------------------------------- purchases (received)
def make_po(po_id, supplier, status, minutes_ago, items, created_by=2, approved_by=1, received_by=2):
    purchases.append(dict(id=po_id, supplier=supplier, status=status, minutes_ago=minutes_ago, items=items,
                          created_by=created_by, approved_by=approved_by if status != "PENDING" else None,
                          received_by=received_by if status == "RECEIVED" else None))


def po_items_for(supplier, lo, hi):
    return [(pid, random.randint(lo, hi), prod[pid]["cost"]) for pid in prod if prod[pid]["sup"] == supplier]


po_id = 0
for s in (1, 2, 3, 4):                           # initial stocking 40 days ago
    po_id += 1
    make_po(po_id, s, "RECEIVED", 40 * 1440, po_items_for(s, 90, 220))
po_id += 1
make_po(po_id, 1, "RECEIVED", 24 * 1440, [(pid, random.randint(60, 120), prod[pid]["cost"]) for pid in (1, 2, 3, 5)])
po_id += 1
make_po(po_id, 2, "PENDING", 3 * 1440, [(6, 100, prod[6]["cost"]), (8, 60, prod[8]["cost"])], approved_by=None)
po_id += 1
make_po(po_id, 3, "APPROVED", 2 * 1440, [(12, 40, prod[12]["cost"]), (17, 40, prod[17]["cost"])])
po_id += 1
make_po(po_id, 4, "CANCELLED", 10 * 1440, [(22, 30, prod[22]["cost"])])

for po in purchases:
    if po["status"] == "RECEIVED":
        for pid, qty, cost in po["items"]:
            add_move(po["minutes_ago"] - 60, pid, "PURCHASE_RECEIPT", qty, cost,
                     f"Received PO-D{po['id']:03d}", "PURCHASE", po["id"], po["received_by"])

# ---------------------------------------------------------------- sales over the last 30 days
payment_methods = ["CASH"] * 5 + ["BANK_TRANSFER"] * 3 + ["OTHER"]
weights = [popularity[i] for i in prod]
sale_id = 0
pool = list(prod)
for day in range(30, -1, -1):
    n_sales = random.randint(4, 9) if day else random.randint(5, 8)
    for _ in range(n_sales):
        sale_id += 1
        minutes_ago = day * 1440 + random.randint(30, 600)
        cashier = random.choice([3, 3, 3, 4, 2])
        items = {}
        for _ in range(random.randint(1, 4)):
            pid = random.choices(pool, weights)[0]
            qty = random.randint(1, 4)
            items[pid] = items.get(pid, 0) + qty
        sales.append(dict(id=sale_id, minutes_ago=minutes_ago, cashier=cashier, items=items,
                          method=random.choice(payment_methods)))

# manual adjustments
add_move(12 * 1440, 3, "ADJUSTMENT", -3, None, "Damaged in storage", "MANUAL", None, 2)
add_move(9 * 1440, 12, "STOCK_OUT", -2, None, "Display unit removed", "MANUAL", None, 2)
add_move(6 * 1440, 7, "STOCK_IN", 12, 1.05, "Supplier sample cartons", "MANUAL", None, 2)

# process chronologically (oldest first) so stock is valid at every point in time
sales.sort(key=lambda s: -s["minutes_ago"])
for s in sales:
    s["lines"] = []
    for pid, qty in s["items"].items():
        qty = min(qty, stock[pid])
        if qty <= 0:
            continue
        s["lines"].append((pid, qty))
        add_move(s["minutes_ago"], pid, "SALE", -qty, prod[pid]["cost"], None, "SALE", s["id"], s["cashier"])
    subtotal = round(sum(prod[p]["price"] * q_ for p, q_ in s["lines"]), 2)
    s["subtotal"] = subtotal
    s["discount"] = round(subtotal * 0.05, 2) if subtotal > 25 and random.random() < 0.25 else 0.0
    s["total"] = round(subtotal - s["discount"], 2)
    s["cogs"] = round(sum(prod[p]["cost"] * q_ for p, q_ in s["lines"]), 2)
    s["status"] = "COMPLETED"

sales = [s for s in sales if s["lines"]]

# a void and a refund (stock restored)
victims = random.sample([s for s in sales if s["minutes_ago"] < 20 * 1440 and s["minutes_ago"] > 1440], 2)
for s, status, reason in ((victims[0], "VOIDED", "Cashier keying error"), (victims[1], "REFUNDED", "Customer returned items")):
    s["status"], s["reason"] = status, reason
    for pid, qty in s["lines"]:
        add_move(s["minutes_ago"] - 30, pid, "VOID" if status == "VOIDED" else "REFUND", qty,
                 prod[pid]["cost"], reason, "SALE", s["id"], 2)

movements.sort(key=lambda m: -m[0])
# recompute quantity_after in chronological order (adjustments were appended out of order)
running = {i: 0 for i in prod}
fixed = []
for m in movements:
    running[m[1]] += m[3]
    assert running[m[1]] >= 0, m
    fixed.append(m[:4] + (running[m[1]],) + m[5:])
movements = fixed
final_stock = dict(running)

# min stock levels: make a few products intentionally low for the dashboard
low_targets = random.sample(list(prod), 4)
for i in prod:
    prod[i]["min"] = final_stock[i] + random.randint(3, 8) if i in low_targets else random.randint(10, 25)
    prod[i]["min"] = min(prod[i]["min"], 60)

for i, p in prod.items():
    lines.append(
        "INSERT INTO products (id, sku, barcode, name, description, category_id, supplier_id, cost_price, selling_price, min_stock) VALUES "
        f"({i}, {q(p['sku'])}, {q('200000000' + str(i).zfill(4))}, {q(p['name'])}, {q('Demo product: ' + p['name'])}, "
        f"{p['cat']}, {p['sup']}, {p['cost']}, {p['price']}, {p['min']});"
    )
    lines.append(f"INSERT INTO inventory (product_id, quantity) VALUES ({i}, {final_stock[i]});")

# purchases
for po in purchases:
    total = round(sum(q_ * c for _, q_, c in po["items"]), 2)
    lines.append(
        "INSERT INTO purchases (id, po_number, supplier_id, status, notes, total_cost, created_by, approved_by, received_by, received_at, created_at, updated_at) VALUES "
        f"({po['id']}, {q('PO-D' + str(po['id']).zfill(3))}, {po['supplier']}, {q(po['status'])}, {q('Demo purchase order')}, {total}, "
        f"{po['created_by']}, {q(po['approved_by'])}, {q(po['received_by'])}, "
        f"{ts(po['minutes_ago'] - 60) if po['status'] == 'RECEIVED' else 'NULL'}, {ts(po['minutes_ago'] + 120)}, {ts(po['minutes_ago'] - 60)});"
    )
    for pid, qty, cost in po["items"]:
        lines.append(f"INSERT INTO purchase_items (purchase_id, product_id, quantity, unit_cost) VALUES ({po['id']}, {pid}, {qty}, {cost});")

# sales
for s in sales:
    rn = f"'SP-' || to_char({ts(s['minutes_ago'])}, 'YYYYMMDD') || '-D{s['id']:04d}'"
    rev = s["status"] != "COMPLETED"
    lines.append(
        "INSERT INTO sales (id, receipt_number, cashier_id, status, subtotal, discount_amount, total, cogs, reversal_reason, reversed_by, reversed_at, created_at) VALUES "
        f"({s['id']}, {rn}, {s['cashier']}, {q(s['status'])}, {s['subtotal']}, {s['discount']}, {s['total']}, {s['cogs']}, "
        f"{q(s.get('reason'))}, {2 if rev else 'NULL'}, {ts(s['minutes_ago'] - 30) if rev else 'NULL'}, {ts(s['minutes_ago'])});"
    )
    for pid, qty in s["lines"]:
        p = prod[pid]
        lines.append(
            "INSERT INTO sale_items (sale_id, product_id, product_name, sku, quantity, unit_price, unit_cost, line_total) VALUES "
            f"({s['id']}, {pid}, {q(p['name'])}, {q(p['sku'])}, {qty}, {p['price']}, {p['cost']}, {round(p['price'] * qty, 2)});"
        )
    lines.append(
        "INSERT INTO payments (sale_id, method, amount, created_at) VALUES "
        f"({s['id']}, {q(s['method'])}, {s['total']}, {ts(s['minutes_ago'])});"
    )

# stock movements (references to sales/purchases resolved above)
for m in movements:
    minutes_ago, pid, mtype, change, after, ucost, reason, rtype, rid, user = m
    lines.append(
        "INSERT INTO stock_movements (product_id, type, quantity_change, quantity_after, unit_cost, reason, reference_type, reference_id, created_by, created_at) VALUES "
        f"({pid}, {q(mtype)}, {change}, {after}, {q(ucost)}, {q(reason)}, {q(rtype)}, {q(rid)}, {user}, {ts(minutes_ago)});"
    )

# audit log samples
for minutes, user, uname, action, etype, eid, details in [
    (3 * 1440, 1, "admin", "LOGIN_SUCCESS", "USER", "1", "Demo login"),
    (2 * 1440, 2, "manager", "PRODUCT_UPDATED", "PRODUCT", "7", "Updated selling price"),
    (12 * 1440, 2, "manager", "STOCK_ADJUSTED", "PRODUCT", "3", "Damaged in storage (-3)"),
    (2 * 1440, 1, "admin", "PURCHASE_APPROVED", "PURCHASE", "7", "Approved PO-D007"),
    (500, 3, "cashier", "LOGIN_SUCCESS", "USER", "3", "Demo login"),
    (900, None, "intruder", "LOGIN_FAILED", "USER", None, "Unknown username"),
]:
    lines.append(
        "INSERT INTO audit_logs (user_id, username, action, entity_type, entity_id, details, ip_address, created_at) VALUES "
        f"({q(user)}, {q(uname)}, {q(action)}, {q(etype)}, {q(eid)}, {q(details)}, '127.0.0.1', {ts(minutes)});"
    )

# advance sequences past explicit ids
for table, mx in (("users", 4), ("categories", 5), ("suppliers", 4), ("products", len(prod)),
                  ("purchases", len(purchases)), ("sales", max(s["id"] for s in sales))):
    lines.append(f"SELECT setval(pg_get_serial_sequence('{table}', 'id'), {mx});")

OUT.write_text("\n".join(lines) + "\n")
print(f"wrote {OUT} ({len(lines)} statements): {len(sales)} sales, {len(movements)} movements")
